export function lonLatToXY(lon: number, lat: number, W: number, H: number): [number, number] {
  return [((lon + 180) / 360) * W, ((90 - lat) / 180) * H];
}

function drawPoly(ctx: CanvasRenderingContext2D, pts: [number,number][], W: number, H: number) {
  if (pts.length < 2) return;
  ctx.beginPath();
  ctx.moveTo(...lonLatToXY(pts[0][0], pts[0][1], W, H));
  for (let i = 1; i < pts.length; i++) ctx.lineTo(...lonLatToXY(pts[i][0], pts[i][1], W, H));
  ctx.closePath();
}

function drawLine(ctx: CanvasRenderingContext2D, pts: [number,number][], W: number, H: number) {
  if (pts.length < 2) return;
  ctx.beginPath();
  ctx.moveTo(...lonLatToXY(pts[0][0], pts[0][1], W, H));
  for (let i = 1; i < pts.length; i++) ctx.lineTo(...lonLatToXY(pts[i][0], pts[i][1], W, H));
}

