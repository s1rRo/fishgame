// ── CLOUD TEXTURE ─────────────────────────────────────────────
export function createCloudTexture(size = 2048): THREE.CanvasTexture {
  const W = size, H = size / 2;
  const c = document.createElement('canvas');
  c.width = W; c.height = H;
  const ctx = c.getContext('2d')!;

  ctx.fillStyle = '#000000';
  ctx.fillRect(0, 0, W, H);

  // Облачные полосы — примерно повторяют атмосферные паттерны
  const cloudBands = [
    { y: H * 0.08, spread: H * 0.06, alpha: 0.4 },  // полярные
    { y: H * 0.28, spread: H * 0.08, alpha: 0.5 },  // умеренные
    { y: H * 0.42, spread: H * 0.04, alpha: 0.25 }, // тропики — меньше
    { y: H * 0.55, spread: H * 0.07, alpha: 0.45 }, // умеренные юг
    { y: H * 0.72, spread: H * 0.06, alpha: 0.5 },
    { y: H * 0.92, spread: H * 0.06, alpha: 0.4 },
  ];

  cloudBands.forEach(band => {
    for (let i = 0; i < 80; i++) {
      const x = Math.random() * W;
      const y = band.y + (Math.random() - 0.5) * band.spread * 2;
      const rw = (30 + Math.random() * 200) * (W / 2048);
      const rh = (8 + Math.random() * 30) * (W / 2048);
      const g = ctx.createRadialGradient(x, y, 0, x, y, Math.max(rw, rh) * 0.5);
      const a = band.alpha * (0.5 + Math.random() * 0.5);
      g.addColorStop(0, `rgba(255,255,255,${a})`);
      g.addColorStop(1, 'rgba(255,255,255,0)');
      ctx.fillStyle = g;
      ctx.beginPath();
      ctx.ellipse(x, y, rw, rh, Math.random() * Math.PI, 0, Math.PI * 2);
      ctx.fill();
    }
  });

  const tex = new THREE.CanvasTexture(c);
  tex.needsUpdate = true;
  return tex;
}
