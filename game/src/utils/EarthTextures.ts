export function createEarthDayTexture(size = 4096): THREE.CanvasTexture {
  const W = size, H = size / 2;
  const canvas = document.createElement('canvas');
  canvas.width = W; canvas.height = H;
  const ctx = canvas.getContext('2d')!;

  // ── Океан ─────────────────────────────────────────────────
  const oceanGrad = ctx.createLinearGradient(0, 0, 0, H);
  oceanGrad.addColorStop(0,    '#0c1b3a'); // полярный
  oceanGrad.addColorStop(0.15, '#1565c0'); // арктика
  oceanGrad.addColorStop(0.35, '#1976d2'); // умеренный
  oceanGrad.addColorStop(0.50, '#0288d1'); // тропики
  oceanGrad.addColorStop(0.65, '#1976d2');
  oceanGrad.addColorStop(0.85, '#1565c0');
  oceanGrad.addColorStop(1,    '#0c1b3a');
  ctx.fillStyle = oceanGrad;
  ctx.fillRect(0, 0, W, H);

  // Небольшая текстура глубины океана
  ctx.globalAlpha = 0.04;
  for (let i = 0; i < 6000; i++) {
    const x = Math.random() * W, y = Math.random() * H;
    ctx.fillStyle = Math.random() > 0.5 ? '#4fc3f7' : '#01579b';
    ctx.fillRect(x, y, 3 + Math.random()*5, 1 + Math.random()*2);
  }
  ctx.globalAlpha = 1;

  // ── Суша ──────────────────────────────────────────────────
  const landPolys: [number,number][][] = [
    NA, GREENLAND, SA, EU, SCANDINAVIA, FINLAND, AF, AS, ARABIA, INDIA,
    INDOCHINA, AU, NZ_N, NZ_S, JAPAN, UK, ICELAND, MADAGASCAR, SRI_LANKA,
    BORNEO, SUMATRA, CUBA,
  ];

  // Базовый цвет суши — умеренный зелёный + коричневый
  landPolys.forEach(poly => {
    drawPoly(ctx, poly, W, H);
    const bb = getBBox(poly, W, H);
    const lg = ctx.createLinearGradient(bb.x0, bb.y0, bb.x1, bb.y1);
    lg.addColorStop(0,   '#2e7d32');
    lg.addColorStop(0.4, '#388e3c');
    lg.addColorStop(0.7, '#558b2f');
    lg.addColorStop(1,   '#4e342e');
    ctx.fillStyle = lg;
    ctx.fill();
  });

  // ── Тропический пояс (насыщенный зелёный) ─────────────────
  ctx.save();
  ctx.globalCompositeOperation = 'source-atop';
  ctx.globalAlpha = 0.18;
  ctx.fillStyle = '#66bb6a';
  ctx.fillRect(0, H * 0.36, W, H * 0.28);
  ctx.restore();

  // ── Пустыни ────────────────────────────────────────────────
  const deserts: [number,number,number,number,string][] = [
    [18,24,35,16, '#c8a96e'],   // Сахара
    [48,26,16,12, '#d2a679'],   // Аравия
    [136,-26,18,12,'#d4a574'],  // Австралия центр
    [64,42,18,10, '#b5a06a'],   // Средняя Азия
    [-68,-26,8,8,  '#d4b896'],  // Атакама
    [18,-24,12,10, '#c9a86c'],  // Намиб/Калахари
  ];
  deserts.forEach(([lon, lat, dlon, dlat, color]) => {
    const [cx, cy] = lonLatToXY(lon, lat, W, H);
    const rx = (dlon / 360) * W;
    const ry = (dlat / 180) * H;
    const g = ctx.createRadialGradient(cx, cy, 0, cx, cy, Math.max(rx, ry));
    g.addColorStop(0, color + 'cc');
    g.addColorStop(1, color + '00');
    ctx.globalAlpha = 0.7;
    ctx.fillStyle = g;
    ctx.beginPath();
    ctx.ellipse(cx, cy, rx, ry, 0, 0, Math.PI * 2);
    ctx.fill();
    ctx.globalAlpha = 1;
  });

  // ── Горы ──────────────────────────────────────────────────
  const ranges: [number,number,number,number][] = [
    [84,32,5,3],    // Гималаи
    [-72,-20,3,15], // Анды
    [-115,47,2,12], // Скалистые горы
    [30,3,1,6],     // Восточная Африка
    [14,47,1,4],    // Альпы
    [86,48,3,3],    // Алтай
    [140,37,0.5,4], // Японские Альпы
    [56,36,2,3],    // Иранское нагорье
  ];
  ranges.forEach(([lon, lat, rx, ry]) => {
    const [cx, cy] = lonLatToXY(lon, lat, W, H);
    const prx = (rx / 360) * W;
    const pry = (ry / 180) * H;
    const g = ctx.createRadialGradient(cx, cy, 0, cx, cy, Math.max(prx, pry));
    g.addColorStop(0, 'rgba(109,76,65,0.7)');
    g.addColorStop(0.6, 'rgba(109,76,65,0.3)');
    g.addColorStop(1, 'rgba(109,76,65,0)');
    ctx.fillStyle = g;
    ctx.beginPath();
    ctx.ellipse(cx, cy, prx, pry, 0, 0, Math.PI * 2);
    ctx.fill();
  });

  // Снежные шапки гор
  ranges.slice(0, 5).forEach(([lon, lat, rx, ry]) => {
    const [cx, cy] = lonLatToXY(lon, lat, W, H);
    const prx = (rx / 360) * W * 0.4;
    const pry = (ry / 180) * H * 0.3;
    ctx.globalAlpha = 0.4;
    ctx.fillStyle = '#eceff1';
    ctx.beginPath();
    ctx.ellipse(cx, cy, prx, pry, 0, 0, Math.PI * 2);
    ctx.fill();
    ctx.globalAlpha = 1;
  });

  // ── Крупные озёра ─────────────────────────────────────────
  const lakePoly = (pts: [number,number][]) => {
    drawPoly(ctx, pts, W, H);
    ctx.fillStyle = '#1565c0';
    ctx.fill();
  };
  lakePoly(CASPIAN);
  lakePoly(BAIKAL);
  lakePoly(VICTORIA);
  lakePoly(TANGANYIKA);
  GREAT_LAKES.forEach(l => lakePoly(l));
  lakePoly(ARAL);
  lakePoly(CHAD);

  // ── Береговые линии ───────────────────────────────────────
  ctx.strokeStyle = 'rgba(0,0,0,0.2)';
  ctx.lineWidth = 0.6;
  landPolys.forEach(poly => {
    drawPoly(ctx, poly, W, H);
    ctx.stroke();
  });

  // ── Реки ──────────────────────────────────────────────────
  RIVERS.forEach(river => {
    ctx.beginPath();
    drawLine(ctx, river.pts, W, H);
    const lw = (river.width / 360) * W * 0.6;
    ctx.strokeStyle = '#1565c0';
    ctx.lineWidth = Math.max(0.8, lw);
    ctx.lineCap = 'round';
    ctx.lineJoin = 'round';
    ctx.globalAlpha = 0.85;
    ctx.stroke();
    ctx.globalAlpha = 1;
  });

  // ── Полярные льды ─────────────────────────────────────────
  drawIceCaps(ctx, W, H);

  // ── Тонкий шум для реализма ────────────────────────────────
  ctx.globalAlpha = 0.03;
  for (let i = 0; i < 8000; i++) {
    const x = Math.random() * W, y = Math.random() * H;
    ctx.fillStyle = Math.random() > 0.5 ? '#ffffff' : '#000000';
    ctx.fillRect(x, y, 1, 1);
  }
  ctx.globalAlpha = 1;

  const tex = new THREE.CanvasTexture(canvas);
  tex.needsUpdate = true;
  return tex;
}

function getBBox(poly: [number,number][], W: number, H: number) {
  let x0=W, x1=0, y0=H, y1=0;
  poly.forEach(([lon, lat]) => {
    const [x, y] = lonLatToXY(lon, lat, W, H);
    if (x < x0) x0=x; if (x > x1) x1=x;
    if (y < y0) y0=y; if (y > y1) y1=y;
  });
  return { x0, x1, y0, y1 };
}

function drawIceCaps(ctx: CanvasRenderingContext2D, W: number, H: number) {
  // Арктика
  const ny  = (H * (90 - 72)) / 180;
  const ni  = ctx.createLinearGradient(0, 0, 0, ny + 30);
  ni.addColorStop(0,    '#e3f2fd');
  ni.addColorStop(0.75, '#e3f2fd');
  ni.addColorStop(1,    'rgba(227,242,253,0)');
  ctx.fillStyle = ni;
  ctx.fillRect(0, 0, W, ny + 30);

  // Антарктида
  const sy = (H * (90 - (-66))) / 180;
  const si = ctx.createLinearGradient(0, sy - 30, 0, H);
  si.addColorStop(0,   'rgba(227,242,253,0)');
  si.addColorStop(0.3, '#d0e8f5');
  si.addColorStop(1,   '#c8e0f0');
  ctx.fillStyle = si;
  ctx.fillRect(0, sy - 30, W, H - sy + 30);
}

